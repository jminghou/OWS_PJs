def calculate_star_brightness(star_name, palace):
    if star_name in brightness_table and palace in brightness_table[star_name]:
        brightness = brightness_table[star_name][palace]
        return str(brightness) if brightness != 0 else ''
    return ''

def get_stars_brightness(stars_info):
    stars_brightness = {}
    # 遍歷所有系統中的星曜
    for system_name, stars in stars_info.items():
        for star, palace in stars.items():
            brightness = calculate_star_brightness(star, palace)
            if brightness:  # 只記錄有亮度數據的星曜
                stars_brightness[star] = brightness
    return stars_brightness
