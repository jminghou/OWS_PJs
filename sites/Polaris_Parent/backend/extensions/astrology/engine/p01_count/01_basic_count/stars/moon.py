def calculate_moon_stars(lunar_month):
    moon_stars_table = {
        '左輔': ['辰', '巳', '午', '未', '申', '酉', '戌', '亥', '子', '丑', '寅', '卯'],
        '右弼': ['戌', '酉', '申', '未', '午', '巳', '辰', '卯', '寅', '丑', '子', '亥'],
        '天馬': ['申', '巳', '寅', '亥', '申', '巳', '寅', '亥', '申', '巳', '寅', '亥'],
        '陰煞': ['寅', '子', '戌', '申', '午', '辰', '寅', '子', '戌', '申', '午', '辰'],
        '天刑': ['酉', '戌', '亥', '子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申'],
        '天姚': ['丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥', '子'],
        '天月': ['戌', '巳', '辰', '寅', '未', '卯', '亥', '未', '寅', '午', '戌', '寅'],
        '天巫': ['巳', '申', '亥', '寅', '巳', '申', '亥', '寅', '巳', '申', '亥', '寅']
    }
    
    moon_stars = {}
    for star, positions in moon_stars_table.items():
        moon_stars[star] = positions[lunar_month - 1]
    
    return moon_stars

def get_moon_stars(lunar_month):
    return calculate_moon_stars(lunar_month)
